-- -----------------------------------------------------------------------------
-- 2. 法规名录 CAS 目录表（真实名录数据）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS msds_regulatory_catalog (
    id              BIGINT       NOT NULL AUTO_INCREMENT,
    category_code   VARCHAR(32)  NOT NULL COMMENT '分类代码',
    sub_category    VARCHAR(64)  NULL COMMENT '名录内细分类（如易制毒第一类 / 易制爆硝酸盐类）',
    chemical_name   VARCHAR(255) NOT NULL COMMENT '名录品名',
    cas_number      VARCHAR(50)  NOT NULL COMMENT 'CAS号',
    catalog_no      VARCHAR(32)  NULL COMMENT '名录序号',
    source_document VARCHAR(255) NULL COMMENT '依据的法规名录',
    remark          VARCHAR(255) NULL COMMENT '备注',
    create_time     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_catalog (category_code, cas_number, chemical_name),
    KEY idx_catalog_cas (cas_number),
    KEY idx_catalog_cat (category_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='MSDS监管分类法规名录（CAS）';

