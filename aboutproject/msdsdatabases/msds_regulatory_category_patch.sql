-- =============================================================================
-- MSDS 监管分类标签增量补丁（幂等，可重复执行）
-- 作用：为「MSDS信息管理」主模块提供 易制毒 / 易制爆 / 剧毒 分类标签的真实数据。
--
-- 数据来源（均为公开权威法规名录，按 CAS 号与 msds_main.cas_number 精确匹配）：
--  1) 易制爆危险化学品名录（2017年版），公安部，2017-05-11
--     https://aj.jdz.gov.cn/bzgf/t37584.shtml
--  2) 剧毒化学品条目汇总（《危险化学品目录（2015版）》中标注「剧毒」的 148 个条目）
--     https://sbc.seu.edu.cn/2014/1020/c5585a105596/pagem.htm
--  3) 易制毒化学品的分类和品种目录（中国禁毒，含 2025-07-20 新增品种，共 47 种）
--     及岳阳市公安局《易制毒化学品目录（2018最新整理）》中 CAS 写法差异的补充条目
--     https://gaj.yueyang.gov.cn/10437/10438/content_1899542.html
--
-- 注意：本脚本只新增表 / 新增数据，不修改、不删除任何现有业务数据。
--      名录中个别条目无独立 CAS 号（如「镁铝粉」「PMK缩水甘油酸酯类物质」），
--      按真实数据原则不予臆造，故不录入。
-- =============================================================================
SET NAMES utf8mb4;

-- -----------------------------------------------------------------------------
-- 1. 分类字典表
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS msds_regulatory_category (
    category_code   VARCHAR(32)  NOT NULL COMMENT '分类代码',
    category_name   VARCHAR(64)  NOT NULL COMMENT '分类全称',
    short_name      VARCHAR(32)  NOT NULL COMMENT '标签短名',
    sort_no         INT          NOT NULL DEFAULT 0 COMMENT '展示顺序',
    color           VARCHAR(20)  NOT NULL DEFAULT '#1677ff' COMMENT '标签主题色',
    description     VARCHAR(500) NULL COMMENT '分类说明',
    source_document VARCHAR(255) NULL COMMENT '依据的法规名录',
    source_url      VARCHAR(500) NULL COMMENT '名录公开来源',
    is_active       TINYINT(1)   NOT NULL DEFAULT 1 COMMENT '是否启用',
    create_time     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (category_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='MSDS监管分类字典';

