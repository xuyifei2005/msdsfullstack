-- -----------------------------------------------------------------------------
-- 3. 化学品-监管分类 关联标签表（由真实名录 × 真实 MSDS 数据生成）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS msds_chemical_category_tag (
    msds_id         BIGINT       NOT NULL COMMENT 'MSDS主表ID',
    category_code   VARCHAR(32)  NOT NULL COMMENT '分类代码',
    sub_category    VARCHAR(64)  NULL COMMENT '名录内细分类',
    catalog_name    VARCHAR(255) NULL COMMENT '命中的名录品名',
    match_type      VARCHAR(16)  NOT NULL DEFAULT 'CAS' COMMENT '匹配方式：CAS / NAME',
    evidence        VARCHAR(500) NULL COMMENT '判定依据（可追溯）',
    source_document VARCHAR(255) NULL COMMENT '依据的法规名录',
    is_confirmed    TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否人工确认（人工校正后不会被脚本覆盖）',
    create_time     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (msds_id, category_code),
    KEY idx_tag_cat (category_code),
    KEY idx_tag_sub (sub_category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='MSDS化学品监管分类标签（真实名录匹配结果）';

-- 3.1 CAS 号精确匹配（主路径）
INSERT IGNORE INTO msds_chemical_category_tag
    (msds_id, category_code, sub_category, catalog_name, match_type, evidence, source_document, is_confirmed)
SELECT m.id, c.category_code, MIN(c.sub_category), MIN(c.chemical_name), 'CAS',
       CONCAT('CAS ', m.cas_number, ' 命中《', MIN(c.source_document), '》条目：', MIN(c.chemical_name)),
       MIN(c.source_document), 0
FROM msds_main m
JOIN msds_regulatory_catalog c
  ON REPLACE(TRIM(m.cas_number), ' ', '') = c.cas_number
GROUP BY m.id, c.category_code;

-- 3.2 名称精确匹配（补充：部分 MSDS 的 CAS 为空或写法不同，仅名称完全一致才纳入）
INSERT IGNORE INTO msds_chemical_category_tag
    (msds_id, category_code, sub_category, catalog_name, match_type, evidence, source_document, is_confirmed)
SELECT m.id, c.category_code, MIN(c.sub_category), MIN(c.chemical_name), 'NAME',
       CONCAT('品名「', m.product_name, '」精确命中《', MIN(c.source_document), '》条目：', MIN(c.chemical_name)),
       MIN(c.source_document), 0
FROM msds_main m
JOIN msds_regulatory_catalog c
  ON m.product_name = c.chemical_name
GROUP BY m.id, c.category_code;

-- 3.3 清理已失效的自动匹配标签（名录订正后可重跑；人工确认的记录保留）
DELETE t FROM msds_chemical_category_tag t
LEFT JOIN msds_main m ON m.id = t.msds_id
WHERE t.is_confirmed = 0 AND (m.id IS NULL OR NOT EXISTS (
    SELECT 1 FROM msds_regulatory_catalog c
    WHERE c.category_code = t.category_code
      AND (REPLACE(TRIM(m.cas_number), ' ', '') = c.cas_number OR m.product_name = c.chemical_name)
));
